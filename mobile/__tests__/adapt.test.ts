/**
 * Adaptive voice: pronouns with correct grammar for every spoken line, the
 * rescuer-state signals, and the safety check that every AI rewrite must pass.
 * Also writes src/voice/adaptedLines.json so tools/render_voice.py can
 * pre-record the he/she versions (no delay when speaking them).
 */
import * as fs from 'fs';
import * as path from 'path';

import { protocols } from '@/protocols';
import systemLines from '@/audio/systemLines.json';
import { assess, CALM_LINE, checkRewrite, initialContext, learn, NUDGE_SUFFIX, personalConfirm, personalize, preface, RELATION_NAMES, voiceRate } from '@/voice/adapt';
import { cards } from '@/voice/answer';

function allLines(): string[] {
  const lines = new Set<string>();
  for (const p of Object.values(protocols)) {
    for (const s of p.steps) {
      s.say.forEach((l) => lines.add(l));
      if (s.kind === 'cpr') [...s.resumeSay, ...s.reminders, ...s.breathsSay, s.depthSay].forEach((l) => lines.add(l));
      if (s.kind === 'hold') s.reminders.forEach((l) => lines.add(l));
      if (s.kind === 'timer') s.doneSay.forEach((l) => lines.add(l));
    }
  }
  cards.forEach((c) => c.say.forEach((l) => lines.add(l)));
  return [...lines];
}

describe('personalize', () => {
  it.each([
    ['Do they respond?', 'he', 'Does he respond?'],
    ['Are they breathing normally?', 'she', 'Is she breathing normally?'],
    ['Can they cough hard, or speak?', 'he', 'Can he cough hard, or speak?'],
    ['Could they have hurt their neck or back?', 'she', 'Could she have hurt her neck or back?'],
    ['Lay them flat on their back, on the floor.', 'he', 'Lay him flat on his back, on the floor.'],
    ["They're responding. Don't start compressions.", 'she', "She's responding. Don't start compressions."],
    ['If they stop responding, tell me.', 'he', 'If he stops responding, tell me.'],
    ['If they get sleepy again, tell me.', 'she', 'If she gets sleepy again, tell me.'],
    ['Keep going until they breathe normally or paramedics take over.', 'he', 'Keep going until he breathes normally or paramedics take over.'],
    ["Only move them if it's not safe where they are.", 'she', "Only move her if it's not safe where she is."],
    ['Note when they last seemed normal.', 'he', 'Note when he last seemed normal.'],
    ['Is it bigger than their palm?', 'she', 'Is it bigger than her palm?'],
    ['If they can cough hard, let them cough.', 'he', 'If he can cough hard, let him cough.'],
    ['Push hard. Push fast.', 'he', 'Push hard. Push fast.'],
  ])('%s (%s)', (line, pronoun, expected) => {
    expect(personalize(line, pronoun as 'he' | 'she')).toBe(expected);
  });

  it('leaves no they/them/their and no broken agreement in any spoken line, and records the variants', () => {
    const variants: string[] = [];
    for (const line of allLines()) {
      for (const p of ['he', 'she'] as const) {
        const out = personalize(line, p);
        expect([line, out]).not.toEqual([line, expect.stringMatching(/\b(they|them|their)\b/i)]);
        // Broken agreement: "he are", "she have"... unless a helper verb comes first ("does he respond", "could she have").
        expect(out).not.toMatch(/(?<!\b(?:does|do|did|can|could|should|will|would|may|might|must) )\b(he|she) (are|do|have|get|stop|breathe|respond)\b/i);
        expect(out).not.toMatch(/\b(does|is) (he|she) (responds|is)\b/i);
        if (out !== line) variants.push(out);
      }
    }
    // "Your dad isn't breathing..." for every relation we recognise, and the calm line.
    for (const confirm of Object.values(systemLines.confirm)) {
      for (const relation of RELATION_NAMES) {
        const out = personalConfirm(confirm, { ...initialContext, relation });
        if (out !== confirm) variants.push(out);
      }
    }
    variants.push(CALM_LINE, NUDGE_SUFFIX);
    fs.writeFileSync(
      path.join(__dirname, '..', 'src', 'voice', 'adaptedLines.json'),
      JSON.stringify({ note: 'GENERATED by __tests__/adapt.test.ts. Adapted versions of spoken lines, for tools/render_voice.py.', lines: [...new Set(variants)].sort() }, null, 2) + '\n',
    );
    expect(variants.length).toBeGreaterThan(40);
  });
});

describe('learning from the rescuer', () => {
  it('picks up who the patient is', () => {
    const c = learn(initialContext, "my dad just collapsed and he's not breathing");
    expect(c).toMatchObject({ relation: 'dad', pronoun: 'he' });
    expect(personalConfirm("Not breathing. We'll do this together.", c)).toBe("Your dad isn't breathing. We'll do this together.");
  });
  it('hears panic and slows down with a calming line first', () => {
    const c = learn(initialContext, 'oh my god please help he is not he is not breathing', 1000);
    expect(c.state).toBe('panicked');
    expect(preface(c, 2000)).toEqual(["I'm right here with you."]);
    expect(voiceRate(c, 2000)).toBeLessThan(1);
    expect(preface(c, 1000 + 60_000)).toEqual([]); // fades after 45 s
  });
  it('hears confusion and slows down more', () => {
    const c = learn(initialContext, "what? I don't understand", 0);
    expect(c.state).toBe('confused');
    expect(voiceRate(c, 10)).toBeLessThan(voiceRate({ ...c, state: 'panicked' }, 10));
  });
});

describe('the AI rewrite check', () => {
  // Real outputs from local models on 2026-10-19, kept as regression cases.
  it('rejects a rewrite that drops "on the floor"', () => {
    expect(checkRewrite('Lay them flat on their back, on the floor.', 'Lay him flat on his back.', 'he')).toMatchObject({ ok: false });
  });
  it('rejects a rewrite that invents a step', () => {
    expect(checkRewrite('Kneel beside their chest.', "Place one hand under Dad's head, one hand under his chest.", 'he')).toMatchObject({ ok: false });
  });
  it('rejects a rewrite that talks to the patient', () => {
    expect(checkRewrite('Lay them flat on their back, on the floor.', 'Lay you flat on your back, on the floor.', 'he')).toMatchObject({ ok: false });
  });
  it('rejects a rewrite that drops a "don\'t"', () => {
    expect(checkRewrite("Don't lift to look.", 'Lift gently to look.', 'he')).toMatchObject({ ok: false });
  });
  it('rejects clipped, telegraphic English (qwen2.5 14B, in the app, 2026-10-19)', () => {
    expect(checkRewrite('Lay them flat on their back, on the floor.', 'Lay him flat on back, floor.', 'he', 'dad')).toMatchObject({ ok: false, reason: 'too clipped' });
    expect(checkRewrite('Heel of one hand on the center of the chest.', 'Heel of one hand on center chest.', 'he', 'dad')).toMatchObject({ ok: false });
    expect(checkRewrite('Tap both shoulders hard and shout.', "Tap dad's shoulders hard and shout.", 'he', 'dad')).toEqual({ ok: true });
  });
  it('accepts a faithful, warmer rewrite', () => {
    expect(checkRewrite('Kneel beside their chest.', "Kneel right beside your dad's chest.", 'he', 'dad')).toEqual({ ok: true });
    expect(checkRewrite('Kneel beside their chest.', "Kneel beside your chest.", 'he', 'dad')).toMatchObject({ ok: false });
    expect(checkRewrite('Kneel beside their chest.', "Now kneel beside Dad's chest.", 'he')).toEqual({ ok: true });
    expect(checkRewrite('Do they respond?', 'Does he respond at all?', 'he')).toEqual({ ok: true });
  });
});

describe('local models, measured', () => {
  // Real outputs recorded on this laptop (CPU only), 10 lines, "your dad", rescuer panicking.
  // Regenerate with tools/adapt_eval.mjs. Rejected lines fall back to the pre-recorded wording.
  const samples = JSON.parse(fs.readFileSync(path.join(__dirname, 'fixtures', 'adapt-samples.json'), 'utf8')) as {
    input: string[];
    out: Record<string, { ms: number; lines: string[] | null }>;
  };

  it('catches every bad line the models produced', () => {
    const q = samples.out['qwen2.5:14b-instruct'].lines!;
    expect(checkRewrite(samples.input[0], q[0], 'he', 'dad')).toMatchObject({ ok: false }); // "gently" added
    expect(checkRewrite(samples.input[2], q[2], 'he', 'dad')).toMatchObject({ ok: false }); // "back" dropped
    expect(checkRewrite(samples.input[6], q[6], 'he', 'dad')).toMatchObject({ ok: false }); // "one" dropped
    for (const model of ['gemma3:4b', 'llama3.2']) {
      expect(checkRewrite(samples.input[1], samples.out[model].lines![1], 'he', 'dad')).toMatchObject({ ok: false, reason: 'grammar' });
    }
    expect(checkRewrite(samples.input[9], samples.out['llama3.2'].lines![9], 'he', 'dad')).toMatchObject({ ok: false, reason: 'grammar' });
  });

  it('writes reports/adapt-eval.json', () => {
    const report = Object.fromEntries(
      Object.entries(samples.out).map(([model, { ms, lines }]) => {
        const verdicts = samples.input.map((original, i) => ({ original, model: lines?.[i] ?? null, ...(lines?.[i] ? checkRewrite(original, lines[i], 'he', 'dad') : { ok: false, reason: 'missing' }) }));
        return [model, { seconds: Math.round(ms / 100) / 10, accepted: verdicts.filter((v) => v.ok).length, of: verdicts.length, verdicts }];
      }),
    );
    fs.mkdirSync(path.join(__dirname, '..', 'reports'), { recursive: true });
    fs.writeFileSync(path.join(__dirname, '..', 'reports', 'adapt-eval.json'), JSON.stringify(report, null, 2) + '\n');
    expect(Object.keys(report).length).toBeGreaterThan(0);
  });
});

describe('alone', () => {
  it('hears that the rescuer is on their own, and the 2-minute line stops saying "switch"', () => {
    const { swapLine } = jest.requireActual('@/cpr/timeline') as typeof import('@/cpr/timeline');
    const c = learn(initialContext, "I'm alone, there's nobody else here");
    expect(c.alone).toBe(true);
    expect(learn(c, 'my brother is here now').alone).toBe(false);
    expect(swapLine(2, true)).toBe('Two minutes. Keep going.');
    expect(swapLine(2)).toBe('Two minutes. Switch with someone if you can.');
  });
});

describe('reading the rescuer: weighted signals', () => {
  it('adds up signals and keeps the evidence', () => {
    const a = assess('oh my god please help he is not he is not breathing');
    expect(a.state).toBe('panicked');
    expect(a.distress).toBeGreaterThanOrEqual(0.85);
    const fired = a.distressSignals.filter((s) => s.evidence).map((s) => [s.name, s.evidence]);
    expect(fired).toEqual([
      ['Pleading', 'oh my god'],
      ['Repetition', 'he is not ×2'],
    ]);
  });
  it('needs more than one weak signal', () => {
    expect(assess('he is not breathing!').state).toBeNull(); // one exclamation mark: 0.25
    expect(assess('HELP!! he is not breathing').state).toBe('panicked'); // shouting + exclamation: 0.5
  });
  it('tells confusion from panic', () => {
    const a = assess("what? I don't understand");
    expect(a.state).toBe('confused');
    expect(a.confusion).toBe(1);
    expect(assess('is he breathing').state).toBeNull();
  });
});
