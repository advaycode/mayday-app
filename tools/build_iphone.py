"""
Build Mayday as an iPhone home-screen app (a web app Safari can install).

    python tools/build_iphone.py                 # -> mobile/dist-iphone, for https://<user>.github.io/mayday/
    python tools/build_iphone.py --base /other   # a different folder on the site

Apple only installs native apps from the App Store, TestFlight or a Mac with
Xcode. A web app added from Safari's Share menu opens full screen with its own
icon, and with the offline cache below it keeps working in airplane mode.

What this adds to the normal web export:
  - manifest.webmanifest and icons, so "Add to Home Screen" makes a real app icon
  - iOS tags: full screen, black status bar, content under the notch with safe areas
  - sw.js, a service worker that stores every file on first open, so the app,
    the voice and the hospital data work with no signal afterwards
  - no text selection or callout on long press (buttons are pressed hard and fast)
  - 404.html and .nojekyll, which GitHub Pages needs for this app

Nothing in Mayday can call 911 or anyone else (see mobile/__tests__/never911.test.ts).
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
MOBILE = ROOT / "mobile"
OUT = MOBILE / "dist-iphone"
BG = "#121110"


def export(base: str):
    env = {k: v for k, v in os.environ.items() if k not in ("EXPO_PUBLIC_PROXY_URL", "EXPO_PUBLIC_TTS_URL")}
    # No laptop servers on a phone: the app runs fully offline (keyword router,
    # recorded voice, offline voice adaptation).
    env.update(MAYDAY_BASE_URL=base, CI="1")
    if OUT.exists():
        shutil.rmtree(OUT)
    subprocess.run("npx expo export -p web --output-dir dist-iphone --clear", cwd=MOBILE, env=env, shell=True, check=True)


def icons():
    src = Image.open(MOBILE / "assets" / "images" / "icon.png").convert("RGBA")
    for name, size in (("apple-touch-icon.png", 180), ("icon-192.png", 192), ("icon-512.png", 512)):
        # iOS shows transparency as black; flatten onto the app background.
        bg = Image.new("RGBA", src.size, BG)
        bg.alpha_composite(src)
        bg.convert("RGB").resize((size, size), Image.LANCZOS).save(OUT / name, optimize=True)


def manifest(base: str):
    (OUT / "manifest.webmanifest").write_text(
        json.dumps(
            {
                "name": "Mayday",
                "short_name": "Mayday",
                "description": "Step-by-step help in an emergency, until help arrives.",
                "start_url": f"{base}/",
                "scope": f"{base}/",
                "display": "standalone",
                "orientation": "portrait",
                "background_color": BG,
                "theme_color": BG,
                "icons": [
                    {"src": f"{base}/icon-192.png", "sizes": "192x192", "type": "image/png"},
                    {"src": f"{base}/icon-512.png", "sizes": "512x512", "type": "image/png"},
                ],
            },
            indent=2,
        ),
        encoding="utf-8",
    )


def service_worker(base: str) -> str:
    files = sorted(
        "/".join(p.relative_to(OUT).parts)
        for p in OUT.rglob("*")
        if p.is_file() and p.name not in ("sw.js", "404.html", ".nojekyll", "metadata.json")
    )
    digest = hashlib.sha256()
    for f in files:
        digest.update(f.encode())
        digest.update((OUT / f).read_bytes())
    version = digest.hexdigest()[:12]
    urls = [f"{base}/"] + [f"{base}/{f}" for f in files if f != "index.html"]
    (OUT / "sw.js").write_text(
        f"""// GENERATED by tools/build_iphone.py. Stores the whole app on first open so it
// works with no signal: protocols, voice clips, hospital data, CPR coach.
const CACHE = 'mayday-{version}';
const FILES = {json.dumps(urls)};

self.addEventListener('install', (event) => {{
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
}});

self.addEventListener('activate', (event) => {{
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('mayday-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
}});

self.addEventListener('fetch', (event) => {{
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // map tiles and the like: network only
  // Every screen is the same single page.
  if (req.mode === 'navigate') {{
    event.respondWith(caches.match('{base}/').then((hit) => hit || fetch(req)));
    return;
  }}
  event.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
}});
""",
        encoding="utf-8",
    )
    return version


def html(base: str):
    path = OUT / "index.html"
    s = path.read_text(encoding="utf-8")
    s = s.replace(
        '<meta name="viewport" content="width=device-width, initial-scale=1, shrink-to-fit=no" />',
        '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />',
    )
    head = f"""
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />
    <meta name="apple-mobile-web-app-title" content="Mayday" />
    <meta name="theme-color" content="{BG}" />
    <meta name="format-detection" content="telephone=no" />
    <link rel="apple-touch-icon" href="{base}/apple-touch-icon.png" />
    <link rel="manifest" href="{base}/manifest.webmanifest" />
    <style id="mayday-iphone">
      html, body {{ background: {BG}; }}
      /* Buttons are pressed hard and fast: no text selection, magnifier or callout. */
      body {{ -webkit-user-select: none; user-select: none; -webkit-touch-callout: none; touch-action: manipulation; overscroll-behavior: none; }}
      input, textarea {{ -webkit-user-select: text; user-select: text; }}
    </style>
  </head>"""
    s = s.replace("</head>", head, 1)
    s = s.replace(
        "</body>",
        f"""<script>
    if ('serviceWorker' in navigator) navigator.serviceWorker.register('{base}/sw.js', {{ scope: '{base}/' }});
  </script>
</body>""",
        1,
    )
    path.write_text(s, encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="/mayday", help="folder the site is served from ('' for the domain root)")
    ap.add_argument("--no-export", action="store_true", help="only redo the iPhone additions")
    base = ap.parse_args().base.rstrip("/")
    if not ap.parse_args().no_export:
        export(base)
    icons()
    manifest(base)
    html(base)
    version = service_worker(base)
    shutil.copy(OUT / "index.html", OUT / "404.html")  # GitHub Pages: deep links open the app
    (OUT / ".nojekyll").write_text("")  # GitHub Pages: serve the _expo/ folder
    size = sum(p.stat().st_size for p in OUT.rglob("*") if p.is_file())
    print(f"iPhone build -> {OUT.relative_to(ROOT)}  ({size / 1e6:.1f} MB, cache {version}, base '{base}/')")


if __name__ == "__main__":
    main()
